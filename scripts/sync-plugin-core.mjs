#!/usr/bin/env node
// scripts/sync-plugin-core.mjs — vendor plugins/core into each plugin's core/ dir.
// Plugins must be self-contained at install time (Cursor/Claude Code load a
// plugin directory, not the monorepo), so the shared modules are COPIED, not
// imported across plugin boundaries. This script is the only writer of those
// copies; `--check` is what the plugins' test suites run to refuse drift.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const GENERATED_HEADER =
  "// GENERATED by scripts/sync-plugin-core.mjs from plugins/core — edit there, then re-run the sync.\n";
const EXCLUDE_DIRS = new Set(["test", "node_modules"]);
const EXCLUDE_FILES = new Set(["package.json", "package-lock.json", "README.md", ".gitignore"]);
const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function walk(dir, rel = "") {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const abs = path.join(dir, name);
    const r = rel ? `${rel}/${name}` : name;
    if (statSync(abs).isDirectory()) {
      if (!EXCLUDE_DIRS.has(name)) out.push(...walk(abs, r));
    } else if (!EXCLUDE_FILES.has(name) && name !== "VENDORED.json") {
      out.push(r);
    }
  }
  return out;
}
const sha = (buf) => createHash("sha256").update(buf).digest("hex");
const isJs = (rel) => rel.endsWith(".js") || rel.endsWith(".mjs");
function stripHeader(text) {
  return text.startsWith(GENERATED_HEADER) ? text.slice(GENERATED_HEADER.length) : text;
}

/** @returns {{ drift: string[] }} */
export function syncCore({ source, targets, check }) {
  const files = walk(source);
  const hashes = {};
  for (const rel of files) hashes[rel] = sha(readFileSync(path.join(source, rel)));
  const drift = [];
  for (const target of targets) {
    const pluginDir = path.dirname(target);
    if (!existsSync(pluginDir)) { console.error(`sync-plugin-core: skip ${target} (no ${pluginDir})`); continue; }
    if (check) {
      if (!existsSync(target)) { drift.push(`${target}: missing (never synced)`); continue; }
      const present = new Set(walk(target));
      for (const rel of files) {
        if (!present.has(rel)) { drift.push(`${target}/${rel}: missing in vendored copy`); continue; }
        const vend = readFileSync(path.join(target, rel));
        const body = isJs(rel) ? Buffer.from(stripHeader(vend.toString("utf8")), "utf8") : vend;
        if (sha(body) !== hashes[rel]) drift.push(`${target}/${rel}: drift (vendored copy differs from plugins/core)`);
      }
      for (const rel of present) if (!(rel in hashes)) drift.push(`${target}/${rel}: extra (not in plugins/core)`);
      let manifest = null;
      try { manifest = JSON.parse(readFileSync(path.join(target, "VENDORED.json"), "utf8")); } catch { /* handled below */ }
      if (!manifest || JSON.stringify(manifest.files) !== JSON.stringify(hashes)) drift.push(`${target}/VENDORED.json: stale manifest`);
      continue;
    }
    rmSync(target, { recursive: true, force: true });
    for (const rel of files) {
      const dst = path.join(target, rel);
      mkdirSync(path.dirname(dst), { recursive: true });
      const src = readFileSync(path.join(source, rel));
      writeFileSync(dst, isJs(rel) ? GENERATED_HEADER + src.toString("utf8") : src);
    }
    writeFileSync(path.join(target, "VENDORED.json"), JSON.stringify({ source: "plugins/core", files: hashes }, null, 2) + "\n");
  }
  return { drift };
}

function parseArgs(argv) {
  const o = { check: false, source: path.join(REPO_ROOT, "plugins", "core"),
    targets: [path.join(REPO_ROOT, "plugins", "claude-code", "core"), path.join(REPO_ROOT, "plugins", "cursor", "core")] };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--check") o.check = true;
    else if (argv[i] === "--source") o.source = path.resolve(argv[++i]);
    else if (argv[i] === "--targets") o.targets = argv[++i].split(",").map((t) => path.resolve(t));
  }
  return o;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const o = parseArgs(process.argv.slice(2));
  const { drift } = syncCore(o);
  if (o.check) {
    if (drift.length) { console.error("plugin core out of sync:\n  " + drift.join("\n  ") + "\nrun: node scripts/sync-plugin-core.mjs"); process.exit(1); }
    console.log("plugin core in sync");
  } else {
    console.log(`synced plugins/core → ${o.targets.filter((t) => existsSync(t)).join(", ")}`);
  }
}
